window.getSiteLang = function getSiteLang() {
  return document.documentElement.dataset.lang === "en" ? "en" : "pt";
};

window.t = function t(key, lang) {
  const dict = window.SITE_I18N[lang || window.getSiteLang()];
  return key.split(".").reduce(function (acc, part) {
    return acc && acc[part] !== undefined ? acc[part] : "";
  }, dict);
};
